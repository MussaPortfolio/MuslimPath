@Composable
fun DocScreen(nav: Nav, id: String) {
    val (title, parts) = docs[id] ?: return
    ListScreen(title = title, onBack = { nav.back() }) {
        parts.forEach { part ->
            item {
                when (part) {
                    is String -> Text(part, style = MaterialTheme.typography.bodyLarge, modifier = Modifier.padding(vertical = 8.dp))
                    is Pair<*, *> -> {
                        Text(part.first as String, style = MaterialTheme.typography.titleMedium, color = MaterialTheme.colorScheme.primary, modifier = Modifier.padding(top = 16.dp, bottom = 4.dp))
                        Text(part.second as String, style = MaterialTheme.typography.bodyLarge)
                    }
                }
            }
        }
    }
}
